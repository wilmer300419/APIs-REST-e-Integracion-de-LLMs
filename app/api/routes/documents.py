"""Endpoints CRUD de documentos (5 endpoints).

Cada ruta documenta en OpenAPI (en inglés): parámetros, ejemplos del cuerpo,
respuesta exitosa y todos los errores posibles con su JSON de ejemplo.
Los docstrings de las funciones se muestran como `description` en Swagger UI.
"""
from __future__ import annotations

from fastapi import APIRouter, Body, Depends, Path, Query, Response, status

from app.api import docs
from app.api.dependencies import get_document_service
from app.schemas.document import DocumentCreate, DocumentResponse, DocumentUpdate
from app.services.document_service import DocumentService

# El 500 aplica a todas las rutas del router, por eso se declara una sola vez aquí.
router = APIRouter(prefix="/documents", tags=["Documents"], responses={**docs.INTERNAL_ERROR})

# Parámetro de ruta reutilizado por GET, PUT y DELETE.
DocumentId = Path(..., ge=1, description="Document identifier (positive integer).",
                  openapi_examples={"existing": {"summary": "An existing document", "value": 1}})


@router.post(
    "",
    response_model=DocumentResponse,
    status_code=status.HTTP_201_CREATED,
    summary="Create a document",
    response_description="The created document, including the server-generated `id` and timestamps.",
    responses={**docs.CONFLICT, **docs.BODY_422},
)
def create_document(
    data: DocumentCreate = Body(..., openapi_examples={
        "with_tags": {
            "summary": "Document with tags",
            "value": {
                "title": "Enrollment guide",
                "content": "To enroll, the student must pay the tuition fee and hand in the student ID card "
                           "at the admissions office before the first day of classes.",
                "tags": ["admissions", "enrollment"],
            },
        },
        "without_tags": {
            "summary": "Document without tags (`tags` is optional)",
            "value": {
                "title": "Library hours",
                "content": "The library is open Monday to Friday from 7am to 9pm and on Saturdays "
                           "from 8am to 1pm.",
            },
        },
    }),
    service: DocumentService = Depends(get_document_service),
):
    """Registers a new document in the knowledge base.

    **Business rules**
    - The `title` must be unique (case-insensitive); otherwise the API answers **409**.
    - `id`, `created_at` and `updated_at` are generated by the server and must not be sent.
    """
    return service.create(data)


@router.get(
    "",
    response_model=list[DocumentResponse],
    summary="List documents",
    response_description="JSON array of documents (an empty `[]` when there are none).",
    responses={**docs.LIST_422},
)
def list_documents(
    skip: int = Query(0, ge=0, description="Number of documents to skip (pagination).",
                      openapi_examples={"first_page": {"summary": "From the beginning", "value": 0}}),
    limit: int = Query(20, ge=1, le=100, description="Maximum number of documents to return (1 to 100).",
                       openapi_examples={"twenty": {"summary": "20 per page", "value": 20}}),
    service: DocumentService = Depends(get_document_service),
):
    """Returns the documents in creation order, using simple `skip`/`limit` pagination."""
    return service.list(skip, limit)


@router.get(
    "/{document_id}",
    response_model=DocumentResponse,
    summary="Get a document by id",
    response_description="The requested document.",
    responses={**docs.NOT_FOUND, **docs.PATH_422},
)
def get_document(document_id: int = DocumentId, service: DocumentService = Depends(get_document_service)):
    """Looks up a document by its identifier. Answers **404** if it does not exist."""
    return service.get(document_id)


@router.put(
    "/{document_id}",
    response_model=DocumentResponse,
    summary="Update a document",
    response_description="The document with the new data and a refreshed `updated_at`.",
    responses={**docs.NOT_FOUND, **docs.CONFLICT, **docs.UPDATE_422},
)
def update_document(
    data: DocumentUpdate = Body(..., openapi_examples={
        "full_replacement": {
            "summary": "Replace every field",
            "value": {
                "title": "Enrollment guide 2026",
                "content": "To enroll, the student must pay the tuition fee and hand in the student ID card "
                           "at the admissions office. The deadline is one week before classes start.",
                "tags": ["admissions", "enrollment", "2026"],
            },
        },
    }),
    document_id: int = DocumentId,
    service: DocumentService = Depends(get_document_service),
):
    """Fully replaces an existing document (PUT semantics: **all** fields must be sent).

    - **404** if the id does not exist.
    - **409** if the new `title` already belongs to *another* document.
    """
    return service.update(document_id, data)


@router.delete(
    "/{document_id}",
    status_code=status.HTTP_204_NO_CONTENT,
    summary="Delete a document",
    response_description="Deleted successfully. The response has no body.",
    responses={**docs.NOT_FOUND, **docs.PATH_422},
)
def delete_document(document_id: int = DocumentId, service: DocumentService = Depends(get_document_service)):
    """Permanently deletes a document. Answers **404** if it does not exist."""
    service.delete(document_id)
    return Response(status_code=status.HTTP_204_NO_CONTENT)
