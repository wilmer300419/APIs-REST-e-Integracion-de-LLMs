"""Esquemas Pydantic de los endpoints de IA (RAG + prompt engineering)."""
from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

Technique = Literal["zero_shot", "few_shot", "chain_of_thought"]


class AskRequest(BaseModel):
    """Question the user wants answered from the knowledge base."""

    model_config = ConfigDict(json_schema_extra={"example": {
        "question": "Where do I hand in my student ID card?",
        "technique": "zero_shot",
        "top_k": 3,
    }})

    question: str = Field(
        ..., min_length=5, max_length=500,
        description="Natural-language question (5 to 500 characters).",
    )
    technique: Technique = Field(
        "zero_shot",
        description="Prompt engineering technique: `zero_shot` (direct instruction, no examples), "
                    "`few_shot` (includes example Q&A pairs to fix the answer format) or "
                    "`chain_of_thought` (step-by-step reasoning before the final answer).",
    )
    top_k: int = Field(
        3, ge=1, le=10,
        description="Maximum number of document chunks used as context (1 to 10).",
    )


class SourceChunk(BaseModel):
    """Document chunk that was retrieved and used as context."""

    document_id: int = Field(..., description="Id of the document the chunk comes from.")
    title: str = Field(..., description="Title of the source document.")
    text: str = Field(..., description="Chunk text (about 80 words).")
    score: float = Field(..., description="Relevance to the question; higher means more relevant.")


class AskResponse(BaseModel):
    """Generated answer together with the sources that support it."""

    model_config = ConfigDict(json_schema_extra={"example": {
        "answer": "Answer: The student ID card must be handed in at the admissions office "
                  "before the first day of classes.\nSource: Enrollment guide.",
        "technique": "few_shot",
        "sources": [{
            "document_id": 1,
            "title": "Enrollment guide",
            "text": "To enroll, the student must pay the tuition fee and hand in the student ID card "
                    "at the admissions office before the first day of classes.",
            "score": 1.342,
        }],
    }})

    answer: str = Field(
        ..., description="Text generated by the LLM. If no relevant context is found, "
                         "it is a fixed notice and the LLM is not called.",
    )
    technique: Technique = Field(..., description="Prompt technique that was used.")
    sources: list[SourceChunk] = Field(
        ..., description="Chunks used as context, ordered by relevance. "
                         "Empty list when no related information was found.",
    )
